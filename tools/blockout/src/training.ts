/**
 * 행군 코스 320,000 — **4구간 스트리밍** (D-08).
 *
 * 전체 훈련 맵 폴리의 35%이며 §12가 "구간 전환 시 히칭이 우려된다"고
 * 남겨둔 항목이다. 그래서 **한 덩어리로 만들지 않는다** — 구간마다 따로
 * 뽑아야 로드·언로드를 실제로 잴 수 있다. 합쳐 놓고 나중에 자르면
 * 자르는 방식이 측정 결과를 바꾼다.
 *
 * 구간당 80,000 tris / 6MB (§3).
 */
export function marchSegment(index: number): readonly Module[] {
  // 구간마다 지형 성격이 다르다. 같은 것을 네 번 복사하면 스트리밍은 재도
  // "구간마다 다른 것이 로드된다"는 조건이 사라진다.
  const terrains = [
    { name: "포장 도로", width: 8, props: "가로등" },
    { name: "야산 임도", width: 5, props: "수목" },
    { name: "하천 둑길", width: 6, props: "배수 구조물" },
    { name: "복귀 도로", width: 8, props: "이정표" },
  ] as const;

  const terrain = terrains[index];
  if (terrain === undefined) {
    throw new Error(`행군 코스 구간은 0~3이다: ${index}`);
  }

  const z0 = index * 200;

  const half = terrain.width / 2;

  return [
    // 노면 타일 10장이 이어져 200m 한 구간이 된다. 끊기면 길이 아니다.
    boxModule(`${terrain.name} 노면`, v(terrain.width, 0.2, 20), lineZ(10, 20, 0, 0, z0), 3),
    boxModule("노견", v(1.5, 0.15, 20), [
      ...lineZ(10, 20, 0, -half - 0.75, z0),
      ...lineZ(10, 20, 0, half + 0.75, z0),
    ], 2),
    boxModule("좌측 사면", v(6, 2.5, 20), lineZ(10, 20, 1.2, -half - 4.5, z0), 3),
    boxModule("우측 사면", v(6, 2.5, 20), lineZ(10, 20, 1.2, half + 4.5, z0), 3),
    cylinderModule(terrain.props, 0.18, 4, lineZ(20, 10, 2, half + 2, z0), 1.5),
    boxModule("구간 표지", v(0.8, 1.2, 0.1), [v(-half - 1.5, 0.6, z0 + 10)], 2),
    boxModule("휴식 지점", v(4, 0.12, 3), [v(half + 3, 0.06, z0 + 100)], 2),
  ];
}

